// 걸음 박자(2026-10-31 선생님: 걸음이 너무 빠르고, 짐을 들면 뛰는 것처럼 보였다).
// 사람은 빨리 갈수록 박자도 조금 빨라지지만 주로 보폭이 길어진다. 1초에 걷는 걸음 수를 사람 박자 안에 둔다:
// 걷기 약 1.5~2.5걸음, 달리기 약 2.6~3.5걸음. 짐이 무거우면(heavy 0~1) 박자를 조금 늦춘다(빨라지지 않게).
// 거의 서 있을 때(초속 0.4m 아래)는 박자도 함께 줄어 다리만 바쁘게 움직이지 않는다.
export const WALK_FAST = 2.6; // 이 빠르기(m/s)까지는 걷기 박자, 그 위는 달리기 박자
export function stepRate(v, heavy = 0) {
  if (!(v > 0)) return 0;
  const r = v <= WALK_FAST ? 1.45 + 0.42 * v : Math.min(3.5, 1.45 + 0.42 * WALK_FAST + 0.2 * (v - WALK_FAST));
  return r * (1 - 0.06 * heavy) * Math.min(1, v / 0.4);
}
